int QmlMobileAudioProxy::vinylDefaultLeadIn(const QString& type) const {
#ifdef __VINYLCONTROL__
    for (const auto& vinylType : kVinylTypes) {
        if (type == QString::fromUtf8(vinylType.name)) {
            return vinylType.leadIn;
        }
    }
#else
    Q_UNUSED(type);
#endif
    return 0;
}

QVariantMap QmlMobileAudioProxy::vinylDeckSettings(int deck) const {
    QVariantMap settings;
#ifdef __VINYLCONTROL__
    const UserSettingsPointer pConfig = QmlConfigProxy::get();
    if (!pConfig || deck < 0 || deck >= kMaximumVinylControlInputs) {
        return settings;
    }
    const QString group = PlayerManager::groupForDeck(deck);
    QString type = pConfig->getValueString(ConfigKey(group, "vinylcontrol_vinyl_type"));
    if (vinylTypes().indexOf(type) < 0) {
        type = QStringLiteral(MIXXX_VINYL_SERATOCV02VINYLSIDEA);
    }
    settings.insert(QStringLiteral("type"), type);
    settings.insert(QStringLiteral("speed"),
            pConfig->getValueString(ConfigKey(group, "vinylcontrol_speed_type")) ==
                            MIXXX_VINYL_SPEED_45
                    ? 45
                    : 33);
    settings.insert(QStringLiteral("leadIn"),
            pConfig->getValue(ConfigKey(group, "vinylcontrol_lead_in_time"),
                    vinylDefaultLeadIn(type)));
    VinylControlManager* pManager = QmlApplicationProxy::vinylControlManager();
    settings.insert(QStringLiteral("inputConnected"),
            pManager ? pManager->vinylInputConnected(deck) : false);
#else
    Q_UNUSED(deck);
#endif
    return settings;
}

void QmlMobileAudioProxy::setVinylDeckSettings(int deck, const QVariantMap& settings) {
#ifdef __VINYLCONTROL__
    const UserSettingsPointer pConfig = QmlConfigProxy::get();
    if (!pConfig || deck < 0 || deck >= kMaximumVinylControlInputs) {
        return;
    }
    const QString group = PlayerManager::groupForDeck(deck);
    const QString type = settings.value(QStringLiteral("type")).toString();
    if (vinylTypes().indexOf(type) >= 0) {
        pConfig->set(ConfigKey(group, "vinylcontrol_vinyl_type"), ConfigValue(type));
    }
    if (settings.contains(QStringLiteral("speed"))) {
        const bool rpm45 = settings.value(QStringLiteral("speed")).toInt() == 45;
        pConfig->set(ConfigKey(group, "vinylcontrol_speed_type"),
                ConfigValue(rpm45 ? QStringLiteral(MIXXX_VINYL_SPEED_45)
                                  : QStringLiteral(MIXXX_VINYL_SPEED_33)));
        // Also as a control, for the spinning record
        ControlObject::set(ConfigKey(group, "vinylcontrol_speed_type"),
                rpm45 ? MIXXX_VINYL_SPEED_45_NUM : MIXXX_VINYL_SPEED_33_NUM);
    }
    // The mode and the cueing are controls, saved by VinylControlManager only
    // on a regular shutdown, which Android often skips
    for (const auto& [name, key] : {std::pair{"mode", "mode_ch%1"}, std::pair{"cueing", "cueing_ch%1"}}) {
        if (!settings.contains(QLatin1String(name))) {
            continue;
        }
        const int value = std::clamp(settings.value(QLatin1String(name)).toInt(), 0, 2);
        ControlObject::set(ConfigKey(group, QStringLiteral("vinylcontrol_") + QLatin1String(name)),
                value);
        pConfig->setValue(ConfigKey(VINYL_PREF_KEY, QString::fromLatin1(key).arg(deck + 1)),
                value);
    }
    if (settings.contains(QStringLiteral("leadIn"))) {
        pConfig->setValue(ConfigKey(group, "vinylcontrol_lead_in_time"),
                std::max(0, settings.value(QStringLiteral("leadIn")).toInt()));
    }
    if (VinylControlManager* pManager = QmlApplicationProxy::vinylControlManager()) {
        pManager->requestReloadConfig();
    }
#else
    Q_UNUSED(deck);
    Q_UNUSED(settings);
#endif
}

int QmlMobileAudioProxy::vinylGainDb() const {
#ifdef __VINYLCONTROL__
    const UserSettingsPointer pConfig = QmlConfigProxy::get();
    const double ratio = pConfig
            ? pConfig->getValue<double>(ConfigKey(VINYL_PREF_KEY, "gain"), 1.0)
            : 1.0;
    return static_cast<int>(std::lround(ratio2db(ratio > 0 ? ratio : 1.0)));
#else
    return 0;
#endif
}

void QmlMobileAudioProxy::setVinylGainDb(int gainDb) {
#ifdef __VINYLCONTROL__
    const UserSettingsPointer pConfig = QmlConfigProxy::get();
    const double ratio = db2ratio(static_cast<double>(std::clamp(gainDb, 0, 44)));
    if (pConfig) {
        pConfig->set(ConfigKey(VINYL_PREF_KEY, "gain"), ConfigValue(QString::number(ratio)));
    }
    ControlObject::set(ConfigKey(VINYL_PREF_KEY, "gain"), ratio);
#else
    Q_UNUSED(gainDb);
#endif
}

