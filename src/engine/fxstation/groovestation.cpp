GrooveStation::GrooveStation()
        : m_sampleRate(48000.f),
          m_swing(0.f),
          m_playing(false),
          m_anySolo(false),
          m_pattern(0),
          m_lastStep(-1),
          m_lastFired(0),
          m_repeat(0),
          m_previousPads{},
          m_repeatIndex{},
          m_previousClear(false) {
    m_pPlay = makeButton(QStringLiteral("play"), true);
    m_pRecord = makeButton(QStringLiteral("record"), true);
    m_pPattern = makeButton(QStringLiteral("pattern"), true, kPatterns);
    m_pKit = makeButton(QStringLiteral("kit"), true, kBanks);
    // A fraction of a step by which the off steps are late
    m_pSwing = makeKnob(QStringLiteral("swing"), 0.0, 0.5, 0.0);
    m_pVolume = makeKnob(QStringLiteral("volume"), 0.0, 1.0, 0.8);
    m_pRepeat = makeButton(QStringLiteral("repeat"), true, kRepeatSettings);
    m_pQuantize = makeButton(QStringLiteral("quantize"), true, 2, 1.0);
    m_pClear = makeButton(QStringLiteral("clear"), false);
    m_pReload = makeButton(QStringLiteral("reload"), false);
    m_pStep = std::make_unique<ControlObject>(key(QStringLiteral("step")));
    m_pStep->set(-1);
    for (int i = 0; i < kBanks; ++i) {
        m_pKitSounds[i] = std::make_unique<ControlObject>(
                key(QStringLiteral("kit_sounds_%1").arg(i + 1)));
        m_pKitSounds[i]->set(i == 0 ? kTracks : 0);
    }
    for (int t = 0; t < kTracks; ++t) {
        const QString track = QString::number(t + 1);
        // The velocity of the hit while held, 0 when released
        m_pPads[t] = makeButton(QStringLiteral("pad_") + track, false);
        m_pMutes[t] = makeButton(QStringLiteral("mute_") + track, true);
        m_pSolos[t] = makeButton(QStringLiteral("solo_") + track, true);
        m_pTrackVolumes[t] = makeKnob(QStringLiteral("volume_") + track, 0.0, 1.0, 0.8);
        for (int s = 0; s < kSteps; ++s) {
            m_pCells[t][s] = makeKnob(
                    QStringLiteral("cell_%1_%2").arg(t + 1).arg(s + 1), 0.0, 1.0, 0.0);
        }
    }
    // A pattern to start with: four on the floor, snare and hats
    for (int s = 0; s < kSteps; s += 4) {
        m_pCells[0][s]->set(1.0);
        m_pCells[3][s + 2]->set(kDefaultVelocity);
    }
    m_pCells[1][4]->set(1.0);
    m_pCells[1][12]->set(1.0);
    for (auto& pattern : m_patterns) {
        for (auto& track : pattern) {
            for (auto& cell : track) {
                cell.store(0.f, std::memory_order_relaxed);
            }
        }
    }
    // [AI-GENERATED DISCLAIMER START: Autonomously generated by an AI agent]
    savePattern(0);
    loadFromFile();
    auto* pSaveTimer = new QTimer(this);
    connect(pSaveTimer, &QTimer::timeout, this, &GrooveStation::saveToFileIfChanged);
    pSaveTimer->start(kSaveIntervalMillis);
    // [AI-GENERATED DISCLAIMER END: Autonomously generated by an AI agent]

    m_pKits = std::make_unique<Instruments>(Instruments::Kind::Groove);
    connect(m_pKits.get(), &Instruments::bankLoaded, this, [this](int index, int sounds) {
        m_pKitSounds[index]->set(sounds);
    });
    connect(m_pReload.get(), &ControlObject::valueChanged, this, [this](double value) {
        if (value > 0) {
            m_pKits->reloadUserBanks();
        }
    });
    m_pKits->reloadUserBanks();
}

GrooveStation::~GrooveStation() {
    saveToFileIfChanged();
}

