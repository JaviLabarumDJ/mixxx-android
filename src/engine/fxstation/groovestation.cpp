void GrooveStation::prepare(float sampleRate) {
    m_sampleRate = sampleRate;
}

void GrooveStation::savePattern(int pattern) {
    for (int t = 0; t < kTracks; ++t) {
        for (int s = 0; s < kSteps; ++s) {
            m_patterns[pattern][t][s].store(
                    static_cast<float>(m_pCells[t][s]->get()), std::memory_order_relaxed);
        }
    }
}

void GrooveStation::loadPattern(int pattern) {
    for (int t = 0; t < kTracks; ++t) {
        for (int s = 0; s < kSteps; ++s) {
            m_pCells[t][s]->set(m_patterns[pattern][t][s].load(std::memory_order_relaxed));
        }
    }
}

bool GrooveStation::audible(int track) const {
    return m_anySolo ? m_pSolos[track]->get() > 0 : m_pMutes[track]->get() <= 0;
}

void GrooveStation::handleControls(double barBeat) {
    // Another pattern: the cells of the last one are kept
    const int pattern = std::clamp(static_cast<int>(m_pPattern->get()), 0, kPatterns - 1);
    if (pattern != m_pattern.load(std::memory_order_relaxed)) {
        savePattern(m_pattern.load(std::memory_order_relaxed));
        loadPattern(pattern);
        m_pattern = pattern;
    }

    const bool clear = m_pClear->get() > 0;
    if (clear && !m_previousClear) {
        for (auto& track : m_pCells) {
            for (auto& pCell : track) {
                pCell->set(0.0);
            }
        }
    }
    m_previousClear = clear;

    m_swing = static_cast<float>(m_pSwing->get());
    m_anySolo = std::any_of(m_pSolos.begin(), m_pSolos.end(), [](const auto& pSolo) {
        return pSolo->get() > 0;
    });

    const bool playing = m_pPlay->get() > 0;
    if (playing != m_playing) {
        m_playing = playing;
        // From the next step, or this one when right on it
        const double position = barBeat * kStepsPerBeat;
        const double step = std::floor(position);
        m_lastFired = static_cast<long long>(step) - (position - step < 0.05 ? 1 : 0);
        if (!playing) {
            m_pStep->set(-1);
            m_lastStep = -1;
        }
    }

    // The pads: a hit now, recorded into the pattern while recording
    const int repeat = std::clamp(static_cast<int>(m_pRepeat->get()), 0, kRepeatSettings - 1);
    m_repeat = repeat;
    for (int t = 0; t < kTracks; ++t) {
        const double velocity = m_pPads[t]->get();
        const bool held = velocity > 0;
        if (held && !m_previousPads[t]) {
            trigger(t, static_cast<float>(std::min(1.0, velocity)));
            if (repeat > 0) {
                m_repeatIndex[t] = static_cast<long long>(
                        std::floor(barBeat * kRepeatRates[repeat]));
            }
            if (m_playing && m_pRecord->get() > 0) {
                const double position = barBeat * kStepsPerBeat;
                const long long step = m_pQuantize->get() > 0
                        ? std::llround(position)
                        : static_cast<long long>(std::floor(position));
                auto& pCell = m_pCells[t][wrapStep(step)];
                pCell->set(std::max(pCell->get(), std::min(1.0, velocity)));
            }
        }
        m_previousPads[t] = held;
    }
}

double GrooveStation::stepPosition(double barBeat) const {
    return barBeat * kStepsPerBeat;
}

void GrooveStation::trigger(int track, float velocity) {
    const int kit = std::clamp(static_cast<int>(m_pKit->get()), 0, kBanks - 1);
    const Bank* pBank = m_pKits->bank(kit);
    const Bank* pFactory = m_pKits->bank(0);
    const Instrument* pInstrument = nullptr;
    if (pBank && pBank->instruments[track].frames() > 0) {
        pInstrument = &pBank->instruments[track];
    } else if (pFactory) {
        pInstrument = &pFactory->instruments[track];
    }
    if (!pInstrument || pInstrument->frames() == 0) {
        return;
    }
    Voice* pFree = nullptr;
    for (auto& voice : m_voices) {
        const bool choked = voice.track == track || (track == kClosedHat && voice.track == kOpenHat);
        if (voice.active && choked && voice.fade == 0.f) {
            voice.fade = 1.f / (kChokeSeconds * m_sampleRate);
        }
        if (!voice.active && !pFree) {
            pFree = &voice;
        }
    }
    if (!pFree) {
        pFree = &*std::max_element(m_voices.begin(), m_voices.end(), [](const Voice& a, const Voice& b) {
            return a.position < b.position;
        });
    }
    pFree->pInstrument = pInstrument;
    pFree->track = track;
    pFree->position = 0.0;
    pFree->rate = pInstrument->sampleRate / m_sampleRate;
    pFree->gain = velocity * static_cast<float>(m_pTrackVolumes[track]->get() * m_pVolume->get());
    pFree->fade = 0.f;
    pFree->active = true;
}

void GrooveStation::playStep(int step) {
    for (int t = 0; t < kTracks; ++t) {
        const double velocity = m_pCells[t][step]->get();
        if (velocity > 0 && audible(t)) {
            trigger(t, static_cast<float>(velocity));
        }
    }
    if (step != m_lastStep) {
        m_lastStep = step;
        m_pStep->set(step);
    }
}

void GrooveStation::process(double barBeat, double previousBarBeat, float* pLeft, float* pRight) {
    Q_UNUSED(previousBarBeat);
    if (m_playing) {
        // The step whose time has come: the off steps (odd) are later by
        // the swing
        const double position = stepPosition(barBeat);
        const long long step = static_cast<long long>(std::floor(position));
        const double swing = (step & 1) ? m_swing : 0.0;
        const long long due = position >= step + swing ? step : step - 1;
        if (due > m_lastFired) {
            m_lastFired = due;
            playStep(wrapStep(due));
        } else if (due < m_lastFired - 2) {
            // The clock jumped back (e.g. the bar was found again)
            m_lastFired = due;
        }
    }

    // Note repeat of the held pads
    if (m_repeat > 0) {
        const long long index = static_cast<long long>(std::floor(barBeat * kRepeatRates[m_repeat]));
        for (int t = 0; t < kTracks; ++t) {
            if (m_previousPads[t] && index != m_repeatIndex[t]) {
                m_repeatIndex[t] = index;
                trigger(t, static_cast<float>(std::min(1.0, m_pPads[t]->get())));
            }
        }
    }

    float left = 0.f;
    float right = 0.f;
    for (auto& voice : m_voices) {
        if (!voice.active) {
            continue;
        }
        const Instrument& sound = *voice.pInstrument;
        const int frames = sound.frames();
        if (voice.position >= frames - 1) {
            voice.active = false;
            continue;
        }
        if (voice.fade > 0.f) {
            voice.gain -= voice.fade;
            if (voice.gain <= 0.f) {
                voice.active = false;
                continue;
            }
        }
        const int index = static_cast<int>(voice.position);
        const float frac = static_cast<float>(voice.position - index);
        const float* pSample = &sound.samples[2 * index];
        left += (pSample[0] + (pSample[2] - pSample[0]) * frac) * voice.gain;
        right += (pSample[1] + (pSample[3] - pSample[1]) * frac) * voice.gain;
        voice.position += voice.rate;
    }
    *pLeft += left;
    *pRight += right;
}

