void GrooveStation::loadFromFile() {
    QFile file(patternsFilePath());
    if (!file.open(QIODevice::ReadOnly)) {
        return;
    }
    const QByteArray data = file.readAll();
    const QJsonObject root = QJsonDocument::fromJson(data).object();
    const QJsonArray patterns = root.value(QStringLiteral("patterns")).toArray();
    if (root.value(QStringLiteral("version")).toInt() != kFileVersion || patterns.isEmpty()) {
        qWarning() << "Groove Station: ignoring the unreadable" << patternsFilePath();
        return;
    }
    for (int p = 0; p < kPatterns && p < patterns.size(); ++p) {
        const QJsonArray tracks = patterns.at(p).toArray();
        for (int t = 0; t < kTracks; ++t) {
            const QJsonArray steps = tracks.at(t).toArray();
            for (int s = 0; s < kSteps; ++s) {
                const double velocity = std::clamp(steps.at(s).toDouble(), 0.0, 1.0);
                m_patterns[p][t][s].store(static_cast<float>(velocity), std::memory_order_relaxed);
            }
        }
    }
    const int pattern = std::clamp(root.value(QStringLiteral("pattern")).toInt(), 0, kPatterns - 1);
    m_pattern = pattern;
    m_pPattern->set(pattern);
    loadPattern(pattern);
    m_pKit->set(std::clamp(root.value(QStringLiteral("kit")).toInt(), 0, kBanks - 1));
    m_pSwing->set(std::clamp(root.value(QStringLiteral("swing")).toDouble(), 0.0, 0.5));
    m_savedData = data;
}

void GrooveStation::saveToFileIfChanged() {
    // The cells of the pattern being edited are in the controls, the others
    // were stored by the engine thread when the pattern changed
    const int current = m_pattern.load();
    QJsonArray patterns;
    for (int p = 0; p < kPatterns; ++p) {
        QJsonArray tracks;
        for (int t = 0; t < kTracks; ++t) {
            QJsonArray steps;
            for (int s = 0; s < kSteps; ++s) {
                const double velocity = p == current
                        ? m_pCells[t][s]->get()
                        : m_patterns[p][t][s].load(std::memory_order_relaxed);
                // Two decimals are plenty for a velocity
                steps.append(std::round(velocity * 100.0) / 100.0);
            }
            tracks.append(steps);
        }
        patterns.append(tracks);
    }
    const QJsonObject root{
            {QStringLiteral("version"), kFileVersion},
            {QStringLiteral("pattern"), current},
            {QStringLiteral("kit"), static_cast<int>(m_pKit->get())},
            {QStringLiteral("swing"), m_pSwing->get()},
            {QStringLiteral("patterns"), patterns},
    };
    const QByteArray data = QJsonDocument(root).toJson(QJsonDocument::Compact);
    if (data == m_savedData) {
        return;
    }
    QDir().mkpath(QFileInfo(patternsFilePath()).absolutePath());
    QSaveFile file(patternsFilePath());
    if (!file.open(QIODevice::WriteOnly) || file.write(data) != data.size() || !file.commit()) {
        qWarning() << "Groove Station: unable to save the patterns to" << patternsFilePath();
        return;
    }
    m_savedData = data;
}
